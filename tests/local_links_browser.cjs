"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const {chromium} = require(process.env.LAZYFISH_BROWSER_MODULE);
const fixture = JSON.parse(fs.readFileSync(process.env.LAZYFISH_BROWSER_FIXTURE, "utf8"));
(async () => {
  const browser = await chromium.launch({executablePath:process.env.LAZYFISH_BROWSER_EXECUTABLE, headless:true, args:["--no-sandbox"]});
  const context = await browser.newContext({viewport:{width:1100,height:850}, locale:"en-US"});
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  const page = await context.newPage(), errors = [], requests = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => requests.push(request.url()));
  try {
    await page.goto(fixture.url + "/?conversation=" + fixture.chat);
    await page.locator("#token").fill(fixture.token); await page.locator("#login button").click();
    const links = page.locator(".markdown .local-path-link");
    await links.first().waitFor();
    assert.equal(await links.count(), 5);
    assert.equal(await page.locator(".markdown li a").innerText(), "aclone");
    assert.equal(await page.locator(".markdown table a").getAttribute("href"), "vscode://file/projects/My%20Report%20(draft).md:12:3");
    assert.equal(await page.locator(".markdown strong a").getAttribute("href"), "vscode://file/projects/a(b(c)).py:42:2");
    assert.equal(await links.nth(3).getAttribute("href"), "vscode://file/projects/%E6%95%B0%E6%8D%AE/%E8%AF%B4%E6%98%8E.md");
    assert.equal(await page.locator('.markdown a[href="https://example.org/docs"]').count(), 1);
    assert.equal(await page.locator('.markdown a[href^="mailto:"]').count(), 1);
    assert.equal(await page.locator('.markdown a[href*="?download=1"]').count(), 1);
    assert.equal(await page.locator('.markdown script,.markdown img,.markdown a[href^="javascript:"],.markdown a[href^="//"]').count(), 0);
    assert.equal(await page.evaluate(() => Boolean(window.compromised)), false);
    assert.ok((await page.locator('.markdown').innerText()).includes('[empty]()'));
    assert.equal(await page.locator('.markdown code a').count(), 0);
    const report = page.locator(".markdown table a"), dialog = page.locator(".local-path-dialog");
    await report.click(); await dialog.waitFor();
    assert.equal(await dialog.getAttribute("aria-label"), "Local path");
    assert.equal(await dialog.locator("code").innerText(), "/projects/My Report (draft).md");
    assert.equal(await dialog.locator("a").getAttribute("href"), "vscode://file/projects/My%20Report%20(draft).md:12:3");
    await dialog.getByRole("button", {name:"Copy path", exact:true}).click();
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), "/projects/My Report (draft).md");
    await page.keyboard.press("Escape"); await dialog.waitFor({state:"detached"});
    assert.equal(await report.evaluate(el => document.activeElement === el), true);
    await page.keyboard.press("Enter"); await dialog.waitFor();
    await dialog.getByRole("button", {name:"Close", exact:true}).click(); await dialog.waitFor({state:"detached"});
    await page.evaluate(() => localStorage.setItem("lazyfish.language", "zh")); await page.reload();
    await page.locator(".markdown li a").click(); await dialog.waitFor();
    assert.equal(await dialog.getAttribute("aria-label"), "\u672c\u5730\u8def\u5f84");
    assert.equal(await dialog.getByRole("button", {name:"\u590d\u5236\u8def\u5f84", exact:true}).count(), 1);
    await page.setViewportSize({width:390, height:780});
    assert.ok(await dialog.evaluate(el => el.getBoundingClientRect().right <= innerWidth && el.scrollWidth <= el.clientWidth));
    await page.screenshot({path:fixture.output + "/local-path-mobile.png"});
    await page.keyboard.press("Escape"); await dialog.waitFor({state:"detached"});
    await page.setViewportSize({width:1100, height:850});
    await page.screenshot({path:fixture.output + "/local-path-links.png"});
    assert.equal(requests.some(url => new URL(url).pathname.startsWith("/projects/")), false);
    assert.deepEqual(errors, []);
    console.log("local Markdown links passed");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
